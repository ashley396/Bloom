#!/usr/bin/env node
/**
 * Regenerates the client-side floral-library-collection.js bundle from the
 * same served catalog the server returns (getPublicFloralLibraryCatalog),
 * so the two can never drift.
 *
 * This used to reimplement its own toLibraryProduct() mapping — a second
 * copy of the same logic that had quietly drifted from the real one: it
 * hardcoded every image's license as { source: "bloom_owned",
 * review_status: "approved" } regardless of the arrangement's actual
 * image_license (most are really "ai_generated_cloudflare_flux" /
 * "needs_review"), and it included every arrangement with zero regard for
 * needs_image_replacement — so the 74 images a real visual QA audit
 * flagged as off-subject (a cake, a rusted light fixture, fish on ice,
 * portraits, landscapes...) still shipped in this bundle even after the
 * server-side catalog was fixed to exclude them, because floral-library-
 * ui.js's mergeCatalog() prefers this bundle over the live server fetch
 * by id. Regenerating from the real served catalog (rather than
 * hand-rolling the mapping again) makes that drift structurally
 * impossible going forward.
 */
import fs from "node:fs";
import path from "node:path";
import { getPublicFloralLibraryCatalog } from "../netlify/functions/_shared/floral-library-core.js";

const root = process.cwd();
const publicDir = path.join(root, "public");

const products = getPublicFloralLibraryCatalog();

const collectionJs = `/**
 * AUTO-GENERATED by scripts/sync-floral-library-catalog.mjs — do not edit.
 * Mirrors getPublicFloralLibraryCatalog() (netlify/functions/_shared/floral-library-core.js)
 * so the client bundle and the live server catalog can't drift.
 * Florisyn Ultra-Realistic Floral Library (${products.length} arrangements
 * — everyday plus Funeral, Sympathy, Birthday, Wedding, Congratulations,
 * Get Well, Hydrangeas, Love & Romance, New Baby, and Plants).
 */
(function (global) {
  "use strict";
  var COLLECTION = ${JSON.stringify(
    products.map((p) => ({
      id: p.id,
      source: p.source,
      name: p.name,
      categories: p.categories,
      short_description: p.short_description,
      description: p.description,
      recipe: p.recipe,
      suggested_retail: p.suggested_retail,
      suggested_cost: p.suggested_cost,
      primary_image: p.primary_image,
      image_license: p.image_license,
      metadata: p.metadata
    })),
    null,
    2
  )};
  if (global) global.FlorisynLibraryCollection = COLLECTION;
  if (typeof module !== "undefined" && module.exports) module.exports = COLLECTION;
})(typeof window !== "undefined" ? window : (typeof globalThis !== "undefined" ? globalThis : this));
`;

fs.writeFileSync(path.join(publicDir, "floral-library-collection.js"), collectionJs);

const manifest = {
  version: 3,
  source: "getPublicFloralLibraryCatalog()",
  total: products.length,
  generated_at: new Date().toISOString()
};
fs.writeFileSync(
  path.join(publicDir, "data/floral-library-everyday-manifest.json"),
  JSON.stringify(manifest, null, 2) + "\n"
);

console.log(`sync-floral-library-catalog: ${products.length} arrangements → floral-library-collection.js`);
