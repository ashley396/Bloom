#!/usr/bin/env node
/**
 * Merges all everyday library JSON batches into API products + client collection.js.
 * Never deletes prior batch files — only additive merge.
 */
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const publicDir = path.join(root, "public");
const dataDir = path.join(publicDir, "data");
// Every floral-library-*.json holding an `arrangements` array (everyday + each
// category file). Sorted for stable output; new categories are picked up on drop-in.
const batchFiles = fs.readdirSync(dataDir)
  .filter((f) => /^floral-library-.*\.json$/.test(f))
  .sort()
  .map((f) => path.join(dataDir, f))
  .filter((f) => { try { return Array.isArray(JSON.parse(fs.readFileSync(f, "utf8")).arrangements); } catch { return false; } });

function loadBatches() {
  const arrangements = [];
  for (const file of batchFiles) {
    if (!fs.existsSync(file)) {
      console.warn(`sync: skip missing ${file}`);
      continue;
    }
    const data = JSON.parse(fs.readFileSync(file, "utf8"));
    arrangements.push(...(data.arrangements || []));
  }
  const ids = arrangements.map((a) => a.id);
  if (new Set(ids).size !== ids.length) {
    throw new Error("Duplicate arrangement ids across batches");
  }
  return arrangements;
}

function toLibraryProduct(a) {
  const retail = Number(a.suggested_retail);
  const batch = a.batch ?? 1;
  const contentHash = a.content_sha256 ? String(a.content_sha256).slice(0, 16) : `h${a.id}`;
  const imageBase = `/assets/floral-library/${a.image}`;
  return {
    id: a.id,
    scope: "master",
    source: "florisyn_everyday",
    name: a.name,
    categories: a.categories || ["Everyday"],
    arrangement_type: a.arrangement_type || "bouquet",
    short_description: a.short_description,
    description: a.description,
    suggested_retail: {
      default: retail,
      min: Math.round(retail * 0.9 * 100) / 100,
      max: Math.round(retail * 1.2 * 100) / 100
    },
    suggested_cost: Math.round(retail * 0.42 * 100) / 100,
    primary_image: {
      url: `${imageBase}?v=${contentHash}`,
      alt: a.alt || `${a.name} ultra-realistic everyday floral arrangement photograph`,
      hash: contentHash
    },
    image_license: {
      source: "bloom_owned",
      attribution: `Florisyn Everyday Collection — batch ${batch}`,
      review_status: "approved"
    },
    recipe: (a.recipe || []).map((r) => ({ name: r.name, qty: r.qty })),
    publish_status: "published",
    tags: ["everyday", "ultra_realistic", a.style, `florisyn_everyday_batch_${batch}`],
    metadata: {
      image_standard: "ultra_realistic_professional_floral_photography",
      launch_quality: "everyday_verified",
      replaceable_by_shop: true,
      style: a.style,
      color_palette: a.color_palette,
      container: a.container,
      mechanics: a.mechanics,
      tools: a.tools,
      foliage: a.foliage,
      instructions: a.instructions,
      why_it_works: a.why_it_works,
      batch
    }
  };
}

const arrangements = loadBatches();
const products = arrangements.map(toLibraryProduct);

const collectionJs = `/**
 * AUTO-GENERATED by scripts/sync-floral-library-catalog.mjs — do not edit.
 * Florisyn Everyday Ultra-Realistic Floral Library (${products.length} arrangements).
 */
(function (global) {
  "use strict";
  var COLLECTION = ${JSON.stringify(
    products.map((p) => ({
      id: p.id,
      source: p.source,
      name: p.name,
      categories: p.categories,
      short_description: p.short_description,
      description: p.description,
      recipe: p.recipe,
      suggested_retail: p.suggested_retail,
      suggested_cost: p.suggested_cost,
      primary_image: p.primary_image,
      image_license: p.image_license,
      metadata: p.metadata
    })),
    null,
    2
  )};
  if (global) global.FlorisynLibraryCollection = COLLECTION;
  if (typeof module !== "undefined" && module.exports) module.exports = COLLECTION;
})(typeof window !== "undefined" ? window : (typeof globalThis !== "undefined" ? globalThis : this));
`;

fs.writeFileSync(path.join(publicDir, "floral-library-collection.js"), collectionJs);

const manifest = {
  version: 2,
  batches: batchFiles.filter((f) => fs.existsSync(f)).map((f) => path.basename(f)),
  total: arrangements.length,
  generated_at: new Date().toISOString()
};
fs.writeFileSync(
  path.join(publicDir, "data/floral-library-everyday-manifest.json"),
  JSON.stringify(manifest, null, 2) + "\n"
);

console.log(`sync-floral-library-catalog: ${products.length} arrangements → floral-library-collection.js`);
