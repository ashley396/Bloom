function normalizeSql(sql) {
  return sql.replace(/\r\n/g, "\n").trimEnd();
}

export function buildBaseline() {
  const sections = BASELINE_SOURCES.map((relativePath) => {
    const absolutePath = path.join(root, relativePath);
    if (!fs.existsSync(absolutePath)) {
      throw new Error(`Missing canonical baseline source: ${relativePath}`);
    }
    const sql = normalizeSql(fs.readFileSync(absolutePath, "utf8"));
    if (/^\s*(begin|commit|rollback)\s*;/im.test(sql)) {
      throw new Error(`Transaction control is forbidden in baseline source: ${relativePath}`);
    }
    return `-- BEGIN SOURCE: ${relativePath}\n${sql}\n-- END SOURCE: ${relativePath}`;
  });

  const body = sections.join("\n\n");
  const digest = crypto.createHash("sha256").update(body).digest("hex");
  const header = [
    "-- Florisyn canonical greenfield baseline.",
    "-- Generated by scripts/build-canonical-baseline.mjs; do not edit manually.",
    "-- Empty projects only. Production requires a separate reviewed reconciliation.",
    `-- Source count: ${BASELINE_SOURCES.length}`,
    `-- Source SHA-256: ${digest}`,
    "",
  ].join("\n");
  return `${header}${body}\n`;
}

export function baselineIsCurrent() {
  const absoluteOutput = path.join(root, output);
  return fs.existsSync(absoluteOutput)
    && fs.readFileSync(absoluteOutput, "utf8") === buildBaseline();
}

function main() {
  const checkOnly = process.argv.includes("--check");
  if (checkOnly) {
    if (!baselineIsCurrent()) {
      console.error(`${output} is missing or stale`);
      process.exitCode = 1;
      return;
    }
    console.log(`${output} is current`);
    return;
  }
  fs.writeFileSync(path.join(root, output), buildBaseline());
  console.log(`Generated ${output}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
